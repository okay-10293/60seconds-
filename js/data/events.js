//         {
//           weight: number,           // 상대 가중치, 합 100 아니어도 됨
//           resultText: string,
//           effects: [ ...effect ]
//         }
//       ]
//     }
//   ]
// }
//
// Effect 종류:
//   { type:'resource', key:'food'|'water', delta:number }
//   { type:'item', itemId, delta:number }              // 음수면 소모
