const cure = () => ({ type: 'cure', target: 'all' });
const lose = (itemId, chance, appendText) => ({ type: 'item', itemId, delta: -1, chance, appendText });
const NONE = (text) => [O(1, text)];
const need = (...ids) => ({ items: ids.map((id) => ({ id, count: 1 })) });

const E = (id, title, minDay, description, choices, conditions) => ({
  id, title, minDay, description, choices, ...(conditions ? { conditions } : {}),
});

